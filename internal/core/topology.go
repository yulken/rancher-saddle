package core

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
)

// TopologyFileName is the name of the file written to the build directory by a
// custom-apply provider (Vagrant) and read back by the orchestrator (Harvester).
// It is the decoupling contract between the two: the provider owns the VM layout
// (names, MACs, IPs, roles) and the orchestrator consumes it to render the PXE
// server configuration, without either package importing the other.
const TopologyFileName = "topology.json"

// HarvesterNode describes one Harvester node VM in the planned topology.
type HarvesterNode struct {
	Name string `json:"name"`
	MAC  string `json:"mac"`
	IP   string `json:"ip"`
	Role string `json:"role"` // "create" (first node) or "join"
}

// Topology is the planned VM layout shared between the Vagrant provider (writer)
// and the Harvester orchestrator (reader) via a topology.json file in the build
// directory.
type Topology struct {
	Gateway string          `json:"gateway"` // libvirt network gateway (host side)
	Subnet  string          `json:"subnet"`
	ISOURL  string          `json:"iso_url"` // URL the installer pulls the ISO from
	Nodes   []HarvesterNode `json:"nodes"`
}

// WriteTopology serializes t to <dir>/topology.json with 0600 permissions.
func WriteTopology(dir string, t *Topology) error {
	data, err := json.MarshalIndent(t, "", "  ")
	if err != nil {
		return fmt.Errorf("failed to marshal topology: %w", err)
	}
	path := filepath.Join(dir, TopologyFileName)
	if err := os.WriteFile(path, data, 0600); err != nil {
		return fmt.Errorf("failed to write topology file %q: %w", path, err)
	}
	return nil
}

// ReadTopology loads and parses <dir>/topology.json.
func ReadTopology(dir string) (*Topology, error) {
	path := filepath.Join(dir, TopologyFileName)
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("failed to read topology file %q (generated by the Vagrant provider): %w", path, err)
	}
	var t Topology
	if err := json.Unmarshal(data, &t); err != nil {
		return nil, fmt.Errorf("failed to parse topology file %q: %w", path, err)
	}
	return &t, nil
}
